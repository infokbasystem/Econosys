import assert from 'node:assert/strict';
import test from 'node:test';
import { buildInquiryPayload, createAutomaticInquiry } from './inquiryPayload.js';

test('inquiry saves retain header fields and only the remaining row IDs', () => {
    const payload = buildInquiryPayload({
        companyId: '7', calculationId: '10', customerId: '25',
        product: 'Box', selectedSupplierId: '20', selectedInquiryRecipientId: '60',
        selectedRecipientYourRef: 'Contact', selectedRecipientTermsOfDelivery: 'DAP',
        selectedRecipientTermsOfPayment: '30 days', selectedRecipientLanguageId: '5',
        customerDeliveryAddressId: '30', deliveryAddress: 'Delivery address',
        answerDueDate: '2026-10-25', ourRef: 'User', isFSC: true,
        inquiryRows: [{ id: -40, calculationRowId: 40 }, { id: 100, calculationRowId: 43 }],
    });
    assert.equal(payload.companyId, 7);
    assert.equal(payload.calculationId, 10);
    assert.equal(payload.customerId, 25);
    assert.equal(payload.selectedSupplierId, 20);
    assert.equal(payload.selectedInquiryRecipientId, 60);
    assert.equal(payload.selectedRecipientYourRef, 'Contact');
    assert.equal(payload.selectedRecipientTermsOfDelivery, 'DAP');
    assert.equal(payload.selectedRecipientTermsOfPayment, '30 days');
    assert.equal(payload.selectedRecipientLanguageId, 5);
    assert.equal(payload.customerDeliveryAddressId, 30);
    assert.equal(payload.deliveryAddress, 'Delivery address');
    assert.equal(payload.answerDueDate, '2026-10-25');
    assert.equal(payload.ourRef, 'User');
    assert.equal(payload.isFSC, true);
    assert.equal(payload.autoGenerated, false);
    assert.deepEqual(payload.calculationRowIds, [40, 43]);
    assert.deepEqual(payload.inquiryRowIds, [100]);
    assert.deepEqual(buildInquiryPayload({ inquiryRows: [] }).calculationRowIds, []);
});

test('automatic creation fetches the legacy draft and saves it before returning its persistent ID', async () => {
    const calls = [];
    const draft = {
        id: 0, companyId: 7, calculationId: 10, customerId: 25, autoGenerated: false,
        product: 'Box', selectedSupplierId: 20, isFSC: true,
        inquiryRows: [{ id: -40, calculationRowId: 40, edition: 1000 }],
    };
    const saved = { ...draft, id: 50 };
    const client = {
        get: async (url) => {
            calls.push(['get', url]);
            return { data: draft };
        },
        post: async (url, payload) => {
            calls.push(['post', url, payload]);
            return { data: saved };
        },
    };
    assert.equal(await createAutomaticInquiry(client, 10), saved);
    assert.deepEqual(calls[0], ['get', '/inquiries/from-calculation/10']);
    assert.equal(calls.length, 2);
    assert.equal(calls[1][1], '/inquiries');
    assert.equal(calls[1][2].autoGenerated, true);
    assert.equal(calls[1][2].selectedSupplierId, 20);
    assert.equal(calls[1][2].isFSC, true);
    assert.deepEqual(calls[1][2].calculationRowIds, [40]);
    assert.equal(draft.autoGenerated, false);
});

test('draft failure is propagated without attempting to save', async () => {
    const failure = new Error('Draft failed');
    await assert.rejects(createAutomaticInquiry({
        get: async () => { throw failure; },
        post: async () => assert.fail('Must not save a failed draft'),
    }, 10), (error) => error === failure);
});

test('save failure is propagated without returning a success-shaped result', async () => {
    const failure = new Error('Save failed');
    await assert.rejects(createAutomaticInquiry({
        get: async () => ({ data: { companyId: 7, calculationId: 10 } }),
        post: async () => { throw failure; },
    }, 10), (error) => error === failure);
});

test('a successful HTTP response without a persistent inquiry ID is rejected', async () => {
    await assert.rejects(createAutomaticInquiry({
        get: async () => ({ data: { companyId: 7, calculationId: 10 } }),
        post: async () => ({ data: { id: 0 } }),
    }, 10), /valid inquiry ID/);
});
