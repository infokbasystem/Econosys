import { parseNullableInt } from './numberUtils.js';

export const buildInquiryPayload = (source) => ({
    companyId: parseNullableInt(source?.companyId) ?? 1,
    calculationId: parseNullableInt(source?.calculationId),
    autoGenerated: Boolean(source?.autoGenerated),
    customerId: parseNullableInt(source?.customerId),
    product: source?.product ?? null,
    material: source?.material ?? null,
    materialThickness: source?.materialThickness ?? null,
    format: source?.format ?? null,
    color: source?.color ?? null,
    construction: source?.construction ?? null,
    customerName: source?.customerName ?? null,
    deliveryAddressName: source?.deliveryAddressName ?? null,
    deliveryAddress: source?.deliveryAddress ?? null,
    deliveryPostalNr: source?.deliveryPostalNr ?? null,
    deliveryPostalAddress: source?.deliveryPostalAddress ?? null,
    deliveryCountry: source?.deliveryCountry ?? null,
    ourRef: source?.ourRef ?? null,
    preparation: source?.preparation ?? null,
    timeOfDelivery: source?.timeOfDelivery ?? null,
    selectedInquiryRecipientId: parseNullableInt(source?.selectedInquiryRecipientId),
    selectedSupplierId: parseNullableInt(source?.selectedSupplierId),
    calculationRowIds: (source?.inquiryRows ?? [])
        .map((row) => parseNullableInt(row?.calculationRowId))
        .filter((rowId) => rowId && rowId > 0),
    selectedRecipientYourRef: source?.selectedRecipientYourRef ?? null,
    selectedRecipientTermsOfDelivery: source?.selectedRecipientTermsOfDelivery ?? null,
    selectedRecipientTermsOfPayment: source?.selectedRecipientTermsOfPayment ?? null,
    selectedRecipientLanguageId: parseNullableInt(source?.selectedRecipientLanguageId),
    answerDueDate: source?.answerDueDate ?? null,
    hideCustomerInfoOnPrint: Boolean(source?.hideCustomerInfoOnPrint),
    createdAt: source?.createdAt ?? null,
    editedAt: source?.editedAt ?? null,
    createdBy: parseNullableInt(source?.createdBy),
    editedBy: parseNullableInt(source?.editedBy),
    customerDeliveryAddressId: parseNullableInt(source?.customerDeliveryAddressId),
    isFSC: Boolean(source?.isFSC),
    inquiryRowIds: Array.isArray(source?.inquiryRows)
        ? source.inquiryRows
            .map((row) => parseNullableInt(row?.id))
            .filter((rowId) => rowId && rowId > 0)
        : [],
});

export const createAutomaticInquiry = async (client, calculationId) => {
    const draft = await client.get(`/inquiries/from-calculation/${calculationId}`);
    const response = await client.post('/inquiries', buildInquiryPayload({
        ...draft.data,
        autoGenerated: true,
    }));
    if (!Number.isInteger(response.data?.id) || response.data.id <= 0) {
        throw new Error('The inquiry creation response did not contain a valid inquiry ID.');
    }
    return response.data;
};
